function T = compare_report_values(R)
%COMPARE_REPORT_VALUES Compare new computations against printed reference.
% Reference numbers are transcribed rounded values from the supplied report.
% They are NEVER assigned to computed results. A mismatch is informative:
% another dataset or changed parameters are not forced to match this report.
    names = {'Fs_Hz';'SampleCount';'PeakCount';'UsedRRCount';'MeanRR_s'; ...
        'HeartRate_bpm';'FIRDelay_ms';'IIR_DC_Gain'; ...
        'FIR_RMS_Ratio';'IIR_RMS_Ratio';'FIR_RelativeChange';'IIR_RelativeChange'; ...
        'FIR_60Hz_dB';'FIR_120Hz_dB';'FIR_180Hz_dB'; ...
        'IIR_60Hz_dB';'IIR_120Hz_dB';'IIR_180Hz_dB'};
    expected = [1800;15000;11;10;0.811389;73.9473;8.055556;1.076204; ...
        0.902845;1.05145;0.626026;0.232952; ...
        46.2567;52.5738;55.8174;33.1245;33.6474;33.2339];
    tolerance = [0;0;0;0;5.1e-7;5.1e-5;5.1e-7;5.1e-7; ...
        5.1e-7;5.1e-6;5.1e-7;5.1e-7;repmat(5.1e-5,6,1)];
    B = R.bandTable;
    if ~isequal(B.Center_Hz,[60;120;180])
        error('ECG:ReferenceTargets', 'Reference comparison requires 60/120/180 Hz.');
    end
    actual = [R.data.Fs;R.data.N;numel(R.peaks.indices);sum(R.peaks.usedRR); ...
        R.peaks.meanRR;R.peaks.heartRate;R.filters.firDelayMs;R.filters.dcIIR; ...
        R.overallTable.RMSRatioToRaw(2:3); ...
        R.overallTable.RelativeDifferenceToRaw(2:3); ...
        B.FIR_Reduction_dB;B.IIR_Reduction_dB];
    difference = abs(actual-expected);
    passed = isfinite(actual) & difference<=tolerance;
    T = table(names,expected,actual,difference,tolerance,passed,'VariableNames', ...
        {'Quantity','ReportedRounded','Computed','AbsoluteDifference','Tolerance','Passed'});
end
