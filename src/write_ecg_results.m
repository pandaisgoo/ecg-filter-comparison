function write_ecg_results(R, folder)
%WRITE_ECG_RESULTS Write newly computed tables and log, but no report/README.
    if ~isfolder(folder), mkdir(folder); end
    writetable(R.peaks.peakTable,fullfile(folder,'r_peak_candidates.csv'));
    writetable(R.peaks.rrTable,fullfile(folder,'rr_intervals.csv'));
    writetable(R.bandTable,fullfile(folder,'band_power.csv'));
    writetable(R.overallTable,fullfile(folder,'signal_changes.csv'));
    writetable(R.probeTable,fullfile(folder,'response_probes.csv'));
    writetable(R.validationTable,fullfile(folder,'validation.csv'));
    if ~isempty(R.referenceComparison)
        writetable(R.referenceComparison,fullfile(folder,'report_comparison.csv'));
    end
    quantities = {'Fs_Hz';'Samples';'LastSample_s';'Duration_N_over_Fs_s'; ...
        'InputMinimum';'InputMaximum';'InputMean';'FIRLength'; ...
        'FIRDelay_ms';'IIRPoleRadius';'IIR_DC_Gain';'CandidatePeaks'; ...
        'UsedRRIntervals';'MeanRR_s';'EstimatedHeartRate_bpm'; ...
        'EvaluationStart_s';'EvaluationEnd_s';'EvaluationSamples'; ...
        'PSDFftLength';'PSDGridSpacing_Hz';'PassedNumericalChecks';'NumericalChecks'};
    values = [R.data.Fs;R.data.N;R.data.t(end);R.data.N/R.data.Fs; ...
        R.data.inputMinimum;R.data.inputMaximum;R.data.inputMean;R.filters.M; ...
        R.filters.firDelayMs;R.filters.poleRadius;R.filters.dcIIR;numel(R.peaks.indices); ...
        sum(R.peaks.usedRR);R.peaks.meanRR;R.peaks.heartRate; ...
        R.evaluation.firstTime;R.evaluation.lastTime;R.evaluation.N; ...
        R.evaluation.fftLength;R.evaluation.df;sum(R.validationTable.Passed); ...
        height(R.validationTable)];
    writetable(table(quantities,values,'VariableNames',{'Quantity','Value'}), ...
        fullfile(folder,'run_summary.csv'));
    text = sprintf([ ...
        'ECG filter comparison\nCode version: %s\nRun time: %s\nMATLAB: %s\n' ...
        'Input file: %s\nFs: %.15g Hz\nSamples: %d\n' ...
        'Input amplitude range: [%.15g, %.15g]\n' ...
        'Input amplitude is not normalized before filtering.\n' ...
        'FIR length: %d\nIIR pole radius: %.15g\nIIR DC gain: %.15g\n' ...
        'FIR delay: %.15g ms\nCandidate peaks: %d\nMean RR: %.15g s\n' ...
        'Estimated rate: %.15g bpm\nEvaluation interval: %.15g to %.15g s\n' ...
        'Numerical checks passed: %d/%d\nFigures generated: %d\n' ...
        'No zero-phase filtering or output time alignment.\n' ...
        'No clinical accuracy claim; no clean reference or manual labels.\n' ...
        'README and formal report were not regenerated.\n'], ...
        R.config.codeVersion,R.runTime,R.matlabVersion,R.data.sourceName, ...
        R.data.Fs,R.data.N,R.data.inputMinimum,R.data.inputMaximum, ...
        R.filters.M,R.filters.poleRadius,R.filters.dcIIR,R.filters.firDelayMs, ...
        numel(R.peaks.indices),R.peaks.meanRR,R.peaks.heartRate, ...
        R.evaluation.firstTime,R.evaluation.lastTime, ...
        sum(R.validationTable.Passed),height(R.validationTable),R.figuresGenerated);
    write_utf8(fullfile(folder,'run_log.txt'),text);
    write_utf8(fullfile(folder,'configuration.json'),jsonencode(R.config));
end

function write_utf8(filename,text)
    [fid,msg] = fopen(filename,'w','n','UTF-8');
    if fid<0, error('ECG:WriteFailed','%s',msg); end
    closer = onCleanup(@() fclose(fid)); %#ok<NASGU>
    fprintf(fid,'%s',text);
end
